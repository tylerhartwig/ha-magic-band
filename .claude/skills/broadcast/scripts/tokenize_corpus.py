def nargs(op, b, i):
    if op == 0x0E: return 1
    if op == 0x0F: return max((b[i+1] >> 5), 1)
    if 0x40 <= op <= 0x5F or 0x80 <= op <= 0x9F: return (op & 3) + 1
    if 0xC0 <= op <= 0xDF: return (op & 3) + 2
    return 0
